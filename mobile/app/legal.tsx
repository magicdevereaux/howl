import { router, useLocalSearchParams } from 'expo-router';
import {
  Linking,
  Pressable,
  ScrollView,
  StyleSheet,
  Text,
  View,
} from 'react-native';

import { WEB_URL } from '../src/config';
import { colors as C } from '../src/theme';

/**
 * Privacy Policy and Terms of Service, reachable from inside the app.
 *
 * Both stores require a reachable privacy policy given that Howl sends push
 * notifications and hosts user-generated content, and GAPS #35 flagged that the
 * web client had `LegalPage.jsx` while mobile linked to nothing at all.
 *
 * Why this is a summary plus an outbound link rather than the full text:
 * duplicating the web page's prose into a second file guarantees the two drift,
 * and legal text that disagrees with itself is worse than a summary. The web
 * page would be the single source of truth — except it is not addressable by
 * URL yet, because the web client uses a `view` state string instead of routes
 * (GAPS #33). Once that lands, `WEB_URL`/privacy and /terms become real deep
 * links and the "Read the full policy" button can point straight at them.
 *
 * What is below is therefore deliberately the substantive disclosure — what is
 * collected, who processes it, and how to get it deleted — not a paraphrase of
 * the styling.
 */

