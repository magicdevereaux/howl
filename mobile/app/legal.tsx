export default function LegalScreen() {
  const params = useLocalSearchParams<{ doc?: string }>();
  const isPrivacy = params.doc !== 'terms';

  const title = isPrivacy ? 'Privacy Policy' : 'Terms of Service';
  const sections = isPrivacy ? PRIVACY : TERMS;
  const fullUrl = `${WEB_URL}`;

  return (
    <View style={styles.shell}>
      <ScrollView contentContainerStyle={styles.scroll}>
        <Pressable
          style={styles.back}
          onPress={() => router.back()}
          accessibilityRole="button"
          accessibilityLabel="Go back"
        >
          <Text style={styles.backText}>‹ Back</Text>
        </Pressable>

        <Text style={styles.title} accessibilityRole="header">{title}</Text>
        <Text style={styles.updated}>Summary — last updated August 2026</Text>

        {sections.map(section => (
          <View key={section.heading} style={styles.section}>
            <Text style={styles.heading} accessibilityRole="header">{section.heading}</Text>
            {section.body.map((line, i) => (
              <Text key={i} style={styles.body}>{line}</Text>
            ))}
          </View>
        ))}

        <Pressable
          style={({ pressed }) => [styles.linkButton, pressed && styles.linkButtonPressed]}
          onPress={() => { void Linking.openURL(fullUrl); }}
          accessibilityRole="link"
          accessibilityLabel={`Read the full ${title} on the web`}
          accessibilityHint="Opens your browser"
        >
          <Text style={styles.linkButtonText}>Read the full policy on the web</Text>
        </Pressable>

        <Pressable
          style={styles.switchDoc}
          onPress={() =>
            router.replace({ pathname: '/legal', params: { doc: isPrivacy ? 'terms' : 'privacy' } })
          }
          accessibilityRole="link"
          accessibilityLabel={isPrivacy ? 'Read the Terms of Service' : 'Read the Privacy Policy'}
        >
          <Text style={styles.switchDocText}>
            {isPrivacy ? 'Terms of Service' : 'Privacy Policy'}
          </Text>
        </Pressable>
      </ScrollView>
    </View>
  );
}

const styles = StyleSheet.create({
  shell:  { flex: 1, backgroundColor: C.bg },
  scroll: { padding: 20, paddingBottom: 48, maxWidth: 720, width: '100%', alignSelf: 'center' },

  back:     { paddingVertical: 12, alignSelf: 'flex-start', minHeight: 44, justifyContent: 'center' },
  backText: { color: C.textSec, fontSize: 15 },

  title:   { fontSize: 26, fontWeight: '700', color: C.text, marginTop: 4, marginBottom: 4 },
  updated: { fontSize: 13, color: C.textSec, marginBottom: 28 },

  section: { marginBottom: 28 },
  heading: { fontSize: 17, fontWeight: '700', color: C.accentHover, marginBottom: 10 },
  body:    { fontSize: 15, lineHeight: 23, color: C.textSec, marginBottom: 10 },

  linkButton: {
    backgroundColor: C.accent,
    borderRadius: 10,
    paddingVertical: 15,
    minHeight: 50,
    alignItems: 'center',
    justifyContent: 'center',
    marginTop: 8,
  },
  linkButtonPressed: { backgroundColor: C.accentHover },
  linkButtonText:    { color: C.text, fontSize: 16, fontWeight: '600' },

  switchDoc:     { alignItems: 'center', paddingVertical: 16, minHeight: 48, justifyContent: 'center' },
  switchDocText: { color: C.textSec, fontSize: 14, textDecorationLine: 'underline' },
});
